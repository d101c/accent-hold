"""Per-key repeat: an xkb option that stops only the accentable keys repeating.

Wayland clients repeat keys themselves and skip the keys the keymap marks as
non-repeating, so marking the accentable letters is enough: holding them
opens the picker instead of typing `eeee`, while arrows, Delete, volume keys
and everything else keep the desktop's native repeat.

The option lives in the user's xkb directory (~/.config/xkb), which
libxkbcommon, and so mutter, reads before the system one.
"""

import ctypes
import ctypes.util

OPTION = 'accenthold:norepeat'
SYMBOLS_NAME = 'accenthold'

RULES = f'''// Generated by Accent Hold (ibus/install.sh). Adds the {OPTION} option.
! option = symbols
  {OPTION} = +{SYMBOLS_NAME}(norepeat)

! include %S/evdev
'''

_lib = None


def _xkb():
    global _lib
    if _lib is None:
        lib = ctypes.CDLL(ctypes.util.find_library('xkbcommon') or 'libxkbcommon.so.0')
        p, u32 = ctypes.c_void_p, ctypes.c_uint32
        lib.xkb_context_new.restype = p
        lib.xkb_context_unref.argtypes = [p]
        lib.xkb_keymap_new_from_names.restype = p
        lib.xkb_keymap_new_from_names.argtypes = [p, p, ctypes.c_int]
        lib.xkb_keymap_unref.argtypes = [p]
        lib.xkb_keymap_min_keycode.restype = u32
        lib.xkb_keymap_min_keycode.argtypes = [p]
        lib.xkb_keymap_max_keycode.restype = u32
        lib.xkb_keymap_max_keycode.argtypes = [p]
        lib.xkb_keymap_key_get_name.restype = ctypes.c_char_p
        lib.xkb_keymap_key_get_name.argtypes = [p, u32]
        lib.xkb_keymap_key_get_syms_by_level.argtypes = [
            p, u32, u32, u32, ctypes.POINTER(ctypes.POINTER(u32))]
        lib.xkb_keysym_to_utf32.restype = u32
        lib.xkb_keysym_to_utf32.argtypes = [u32]
        _lib = lib
    return _lib


class _Names(ctypes.Structure):
    _fields_ = [(n, ctypes.c_char_p) for n in ('rules', 'model', 'layout', 'variant', 'options')]


def accent_keys(layouts, chars):
    """Names of the keys (e.g. 'AD03') typing one of `chars` on any layout.

    `layouts` are GNOME xkb ids such as 'fr' or 'de+nodeadkeys'. Only the
    first two levels (plain and Shift) count: AltGr symbols keep repeating.
    """
    xkb = _xkb()
    ctx = xkb.xkb_context_new(0)
    keys = set()
    try:
        for xkb_id in layouts:
            layout, _, variant = xkb_id.partition('+')
            names = _Names(b'evdev', b'pc105', layout.encode(), variant.encode(), b'')
            keymap = xkb.xkb_keymap_new_from_names(ctx, ctypes.byref(names), 0)
            if not keymap:
                continue
            try:
                for code in range(xkb.xkb_keymap_min_keycode(keymap),
                                  xkb.xkb_keymap_max_keycode(keymap) + 1):
                    if _types(xkb, keymap, code) & chars:
                        name = xkb.xkb_keymap_key_get_name(keymap, code)
                        if name:
                            keys.add(name.decode())
            finally:
                xkb.xkb_keymap_unref(keymap)
    finally:
        xkb.xkb_context_unref(ctx)
    return sorted(keys)


def _types(xkb, keymap, code):
    out = set()
    syms = ctypes.POINTER(ctypes.c_uint32)()
    for level in (0, 1):
        for i in range(xkb.xkb_keymap_key_get_syms_by_level(keymap, code, 0, level, ctypes.byref(syms))):
            cp = xkb.xkb_keysym_to_utf32(syms[i])
            if cp:
                out.add(chr(cp))
    return out


def symbols(keys):
    body = '\n'.join(f'    key <{k}> {{ repeat = No }};' for k in keys)
    return f'''// Generated by Accent Hold (ibus/install.sh): accentable keys do not repeat.
partial hidden xkb_symbols "norepeat" {{
{body}
}};
'''
